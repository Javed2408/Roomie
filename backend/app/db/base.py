"""The base class every database model inherits from, plus shared columns.

A "model" is a Python class that describes one database table. SQLAlchemy
collects every model that inherits from `Base` into `Base.metadata`, which
Alembic compares with the real database to work out migrations.
"""

import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import DateTime, MetaData, Uuid, func, text
from sqlalchemy import Enum as SqlEnum
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Gives every constraint and index a predictable name, for example
# "uq_users_email". Without this the database invents names, and a later
# migration cannot reliably refer to the thing it wants to change.
# PostgreSQL limits names to 63 characters, so these patterns are kept short.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UuidPrimaryKeyMixin:
    """A random UUID primary key, generated by the database."""

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
    )


class CreatedAtMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )


class TimestampMixin(CreatedAtMixin):
    """`created_at`, and `updated_at` which changes on every update."""

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )


def enum_type(enum_class: type[StrEnum], name: str, length: int = 30) -> SqlEnum:
    """A column type for a fixed set of values, such as a status.

    The value is stored as ordinary text, and a CHECK constraint named
    "ck_<table>_<name>" rejects anything outside the allowed set. This is
    as safe as a native PostgreSQL enum type, but adding a value later is
    a simple migration instead of an awkward one.
    """
    return SqlEnum(
        enum_class,
        name=name,
        native_enum=False,
        length=length,
        create_constraint=True,
        validate_strings=True,
    )
