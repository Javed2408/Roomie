"""Private storage for verification documents, and checks on uploaded files.

The storage is "private" in a strict sense: nothing in it has a web
address. A file can only leave through an API endpoint that first checks
who is asking (see app/api/v1/documents.py).

`PrivateStorage` is an interface. `LocalPrivateStorage` keeps files in a
folder on this machine, which suits development. An S3-compatible version
implementing the same three methods can replace it at deployment without
any other code changing.
"""

from __future__ import annotations

import hashlib
import re
import secrets
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from fastapi import UploadFile

from app.core.config import get_settings
from app.core.errors import BusinessRuleError, NotFoundError

# A storage key is generated by us and looks like "ab/abcdef...". Anything
# else is refused, so a key can never point outside the storage folder.
_KEY_PATTERN = re.compile(r"^[0-9a-f]{2}/[0-9a-f]{40}$")


class PrivateStorage(Protocol):
    def save(self, key: str, data: bytes) -> None: ...
    def read(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


def new_storage_key() -> str:
    """A random key. It reveals nothing about the file or its owner."""
    name = secrets.token_hex(20)
    return f"{name[:2]}/{name}"


class LocalPrivateStorage:
    def __init__(self, root: Path) -> None:
        self._root = root

    def _path(self, key: str) -> Path:
        if not _KEY_PATTERN.fullmatch(key):
            raise ValueError("Invalid storage key.")
        return self._root / key

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def read(self, key: str) -> bytes:
        path = self._path(key)
        if not path.is_file():
            raise NotFoundError("This document is no longer available.")
        return path.read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


@lru_cache
def get_storage() -> PrivateStorage:
    return LocalPrivateStorage(get_settings().storage_dir)


# --- Checking uploads ---------------------------------------------------


@dataclass(frozen=True)
class ValidatedFile:
    data: bytes
    content_type: str
    sha256: str
    original_filename: str | None


# The first bytes of a file identify its real type. The browser's claimed
# type and the file's name are both ignored: either can say anything.
_SIGNATURES: list[tuple[bytes, str]] = [
    (b"%PDF-", "application/pdf"),
    (b"\xff\xd8\xff", "image/jpeg"),
    (b"\x89PNG\r\n\x1a\n", "image/png"),
]

ALLOWED_TYPES_TEXT = "PDF, JPEG or PNG"


def _detect_type(data: bytes) -> str | None:
    for signature, content_type in _SIGNATURES:
        if data.startswith(signature):
            return content_type
    return None


def _clean_filename(name: str | None) -> str | None:
    """Keep only a short, harmless display name. It is never used as a path."""
    if not name:
        return None
    base = name.replace("\\", "/").rsplit("/", 1)[-1]
    cleaned = "".join(ch for ch in base if ch.isprintable() and ch not in '<>:"|?*').strip()
    return cleaned[:255] or None


async def read_validated_upload(upload: UploadFile, max_bytes: int) -> ValidatedFile:
    """Read an uploaded file, refusing it if it is too big or the wrong type.

    Passing these checks means only "this is a PDF or image of acceptable
    size". It says nothing about whether the document is genuine. That is
    a judgement for a human reviewer, which is why nothing is ever
    approved automatically.
    """
    # Read one byte more than allowed: enough to know it is too big,
    # without loading an enormous file into memory.
    data = await upload.read(max_bytes + 1)
    if len(data) > max_bytes:
        megabytes = max_bytes / (1024 * 1024)
        raise BusinessRuleError(f"The file is too large. The limit is {megabytes:g} MB.")
    if not data:
        raise BusinessRuleError("The file is empty.")

    content_type = _detect_type(data)
    if content_type is None:
        raise BusinessRuleError(f"Upload a {ALLOWED_TYPES_TEXT} file.")

    return ValidatedFile(
        data=data,
        content_type=content_type,
        sha256=hashlib.sha256(data).hexdigest(),
        original_filename=_clean_filename(upload.filename),
    )
